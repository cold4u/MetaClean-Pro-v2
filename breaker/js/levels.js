class ProceduralBreakerGenerator {
  static generate(levelNum) {
    const cols = 9;
    const rows = 6;
    const grid = [];
    const types = [1, 2, 3, 4, 5, 6, 7, 8];

    for (let r = 0; r < rows; r++) {
      const row = [];
      for (let c = 0; c < cols; c++) {
        if (Math.random() < 0.25) {
          row.push(0); // empty gap
        } else {
          const rand = Math.random();
          if (rand < 0.5) row.push(types[Math.floor(Math.random() * 5)]); // color brick
          else if (rand < 0.7) row.push(6); // armored
          else if (rand < 0.85) row.push(7); // explosive
          else row.push(8); // powerup
        }
      }
      grid.push(row);
    }

    return {
      id: levelNum,
      name: `Quantum Sector #${levelNum}`,
      cols,
      rows,
      grid,
      isProcedural: true
    };
  }
}

